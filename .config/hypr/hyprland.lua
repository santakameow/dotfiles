-- Games permitted to tear when general.allow_tearing is enabled.
-- Class regexes, not window titles; inspect a running game with `hyprctl clients`.
-- Fullscreen with no visible overlays is also required. This does not change in-game VSync.
local tearing_game_classes = {
    [[osu!]],
    [[steam_app_22490]],       -- Fallout: New Vegas (enplczru)
    [[(?i:falloutnv\.exe)]],   -- Wine fallback class; verify when the game is running
    [[horizon]],
}

